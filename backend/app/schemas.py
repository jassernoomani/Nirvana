import datetime as dt
import re
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator  # type: ignore[reportMissingImports]


class MenuItemCreate(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid", allow_inf_nan=False)
    name: str = Field(min_length=1, max_length=100)
    description: str | None = Field(default=None, max_length=500)
    price: float = Field(gt=0)
    category: str = Field(min_length=1, max_length=50)
    is_available: bool = True
    preparation_minutes: int = Field(default=15, ge=1, le=240)
    is_vegetarian: bool = False
    image_url: str | None = Field(default=None, pattern=r"^/assets/dishes/[a-zA-Z0-9_-]+\.(?:png|jpg|webp)$")


class MenuItem(MenuItemCreate):
    id: int
    # Read-only: derived from the recipe's ingredients.
    allergens: list[str] = []


class MenuItemPatch(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True, extra="forbid", allow_inf_nan=False)
    name: str = Field(default=None, min_length=1, max_length=100)
    description: str | None = Field(default=None, max_length=500)
    price: float = Field(default=None, gt=0)
    category: str = Field(default=None, min_length=1, max_length=50)
    is_available: bool = Field(default=None)
    preparation_minutes: int = Field(default=None, ge=1, le=240)
    is_vegetarian: bool = Field(default=None)
    image_url: str | None = Field(default=None, pattern=r"^/assets/dishes/[a-zA-Z0-9_-]+\.(?:png|jpg|webp)$")


class MenuPage(BaseModel):
    items: list[MenuItem]
    total: int
    page: int
    page_size: int


EMAIL_PATTERN = r"^[^@\s]+@[^@\s]+\.[^@\s]+$"


class RegisterRequest(BaseModel):
    # Unknown fields such as "role" are ignored: public sign-up always creates a customer.
    model_config = ConfigDict(extra="ignore")
    email: str = Field(max_length=254, pattern=EMAIL_PATTERN)
    full_name: str = Field(min_length=1, max_length=100)
    password: str = Field(min_length=8, max_length=128)

    # Trim email and name (never the password) before the length and format checks.
    @field_validator("email", "full_name", mode="before")
    @classmethod
    def strip_text(cls, value):
        return value.strip() if isinstance(value, str) else value


class LoginRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    email: str = Field(min_length=1, max_length=254)
    password: str = Field(min_length=1, max_length=128)


class User(BaseModel):
    id: int
    email: str
    full_name: str
    role: str
    is_vegetarian: bool


class CheckoutLine(BaseModel):
    model_config = ConfigDict(extra="forbid")
    menu_item_id: int = Field(ge=1)
    quantity: int = Field(ge=1, le=99)


class CheckoutRequest(BaseModel):
    # Only dish ids and quantities are accepted: prices and totals sent by the
    # client are rejected, the server computes them.
    model_config = ConfigDict(extra="forbid")
    items: list[CheckoutLine] = Field(max_length=50)
    # Generated by the client once per checkout; resubmitting it returns the same order.
    idempotency_key: str = Field(min_length=8, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")


class OrderLine(BaseModel):
    menu_item_id: int
    name: str
    quantity: int
    unit_price: float
    line_total: float


class OrderReview(BaseModel):
    rating: int
    comment: str | None
    created_at: str


class Order(BaseModel):
    id: int
    reference: str
    status: str
    total: float
    created_at: str
    items: list[OrderLine]
    # The customer's own review of this order, if they wrote one.
    review: OrderReview | None = None


class ReservationRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")
    date: dt.date
    time: str = Field(pattern=r"^([01]\d|2[0-3]):[0-5]\d$")
    party_size: int = Field(ge=1, le=20)
    contact_phone: str | None = Field(default=None, max_length=30)
    notes: str | None = Field(default=None, max_length=300)

    @field_validator("contact_phone", "notes", mode="before")
    @classmethod
    def blank_to_none(cls, value):
        if isinstance(value, str):
            value = value.strip()
            return value or None
        return value

    @field_validator("contact_phone")
    @classmethod
    def phone_digits(cls, value):
        if value is not None and not re.fullmatch(r"\+?[0-9 ().-]{6,30}", value):
            raise ValueError("Enter a valid phone number (digits, spaces and + only)")
        return value


