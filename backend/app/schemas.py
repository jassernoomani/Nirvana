KitchenStatus = Literal["pending", "preparing", "ready", "served"]


class StatusChange(BaseModel):
    model_config = ConfigDict(extra="forbid")
    # The status the screen showed; the change is refused if the order has moved on since.
    from_status: KitchenStatus
    to_status: KitchenStatus


class KitchenOrder(BaseModel):
    id: int
    reference: str
    status: str
    created_at: str
    status_since: str
    customer_name: str | None
    item_count: int
    longest_preparation_minutes: int
    items: list[OrderLine]


class PrepTimeEstimate(BaseModel):
    minutes: int
    reason: str
    source: Literal["ai", "fallback"]
    orders_ahead: int


class ReviewRequest(BaseModel):
    # No author or order fields: the author is the signed-in customer and the
    # order comes from the URL, so nobody can post as someone else.
    model_config = ConfigDict(extra="forbid")
    rating: int = Field(ge=1, le=5)
    comment: str = Field(max_length=1000)

    @field_validator("comment", mode="before")
    @classmethod
    def trim(cls, value):
        return value.strip() if isinstance(value, str) else value

    @field_validator("comment")
    @classmethod
    def long_enough(cls, value):
        if len(value) < 3:
            raise ValueError("Please write a short comment (at least 3 characters)")
        return value


class PublicReview(BaseModel):
    rating: int
    comment: str
    author: str
    created_at: str


class ReviewSummary(BaseModel):
    average_rating: float | None
    review_count: int
    reviews: list[PublicReview]
